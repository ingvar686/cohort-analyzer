const assert=require('node:assert/strict');
const {evaluate,validate,validDay}=require('./engine.js');
const branch={id:1,widgets:[{id:10},{id:11}],categories:[{id:20},{id:21},{id:99}]};
const rule={id:'a',name:'Website → SEO',widgetId:10,categoryId:20,clientMode:'no_visits',trigger:'booking',enabled:true,startDate:'',endDate:''};
const event={id:'e1',clientId:100,client:'Synthetic',branchId:1,widgetId:10,priorVisits:0,explicitNew:true,createdAt:'2026-11-18T10:00:00',arrived:false,paidInFull:false,categories:[99]};
const one=(overrides={},ruleOverrides={},settings={protectFirstSource:true})=>evaluate([{...event,...overrides}],[{...rule,...ruleOverrides}],settings,branch)[0];
assert.deepEqual(validate(rule,branch),[]);
assert.equal(validDay('2026-02-30'),false);
assert.ok(validate({...rule,categoryId:888},branch).length);
assert.ok(validate({...rule,startDate:'2026-12-01',endDate:'2026-01-01'},branch).length);
assert.ok(validate({...rule,id:'b'},branch,[rule]).length,'Duplicate widget mapping must be rejected');
assert.equal(one().status,'add');
assert.deepEqual(one().after,[99,20],'Existing categories must remain');
assert.equal(one({priorVisits:1}).status,'skip');
assert.equal(one({priorVisits:null}).status,'skip','Unknown history must not be treated as zero');
assert.equal(one({explicitNew:null},{clientMode:'explicit'}).status,'skip');
assert.equal(one({explicitNew:false},{clientMode:'explicit'}).status,'skip');
assert.equal(one({explicitNew:true},{clientMode:'explicit'}).status,'add');
assert.equal(one({priorVisits:8},{clientMode:'any'}).status,'add');
assert.equal(one({branchId:2}).status,'skip');
assert.equal(one({cancelled:true}).status,'skip');
assert.equal(one({},{enabled:false}).status,'skip');
assert.equal(one({},{startDate:'2026-12-01'}).status,'skip');
assert.equal(one({},{endDate:'2026-11-01'}).status,'skip');
assert.equal(one({createdAt:'unknown'},{startDate:'2026-01-01'}).status,'skip');
assert.equal(one({},{trigger:'paid'}).status,'skip');
assert.equal(one({arrived:true,paidInFull:false},{trigger:'paid'}).status,'skip');
assert.equal(one({arrived:true,paidInFull:true},{trigger:'paid'}).status,'add');
assert.equal(one({paidInFull:true,arrived:false},{trigger:'paid'}).status,'skip','Payment alone must not imply an attended visit');
assert.equal(one({firstSourceWidgetId:11}).status,'skip');
assert.equal(one({firstSourceWidgetId:11},{},{protectFirstSource:false}).status,'add');
assert.equal(one({categories:[20,99]}).status,'existing');
const original=structuredClone(event);
const repeated=evaluate([event,event],[rule],{protectFirstSource:true},branch);
assert.deepEqual(repeated.map(x=>x.status),['add','skip']);
assert.match(repeated[1].reason,/Повторное событие/);
assert.deepEqual(event,original,'Preview must not mutate its inputs');
const sameClient=evaluate([event,{...event,id:'e2'}],[rule],{protectFirstSource:true},branch);
assert.equal(sameClient[1].status,'existing','A second booking for one client must not re-add the category');
const laterPaid=evaluate([event,{...event,arrived:true,paidInFull:true}],[{...rule,trigger:'paid'}],{protectFirstSource:true},branch);
assert.deepEqual(laterPaid.map(x=>x.status),['skip','add'],'A waiting event must not suppress a later paid update');
const firstSource=evaluate([event,{...event,id:'e3',widgetId:11}],[rule,{...rule,id:'b',widgetId:11,categoryId:21}],{protectFirstSource:true},branch);
assert.match(firstSource[1].reason,/первый источник/);
console.log('Passed: branch isolation, new/unknown clients, explicit flags, triggers and paid visits, campaign dates, category preservation, first-source protection, duplicate events and immutable inputs.');

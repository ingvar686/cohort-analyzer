const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(require.resolve('../dashboards/campaign-comparison.js'), 'utf8');
const memory = new Map();
const storage = {getItem: key => memory.get(key) ?? null, setItem: (key, value) => memory.set(key, value)};
const escape = value => String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;').replaceAll("'", '&#39;');
function session() {
  const context = vm.createContext({DB: {connection_id: 'account-a', location: {id: 1}}, language: 'ru', localStorage: storage, htmlSafe: escape, campaignLabel: name => name, monthLabel: month => month});
  vm.runInContext(source, context);
  return context;
}
let app = session();
app.saveCampaignNote('Instagram', '', 'Общая стратегия');
app.saveCampaignNote('Instagram', '2026-05', '  Женщины 25–45\nРадиус 3 км  ');
app.saveCampaignNote('Instagram', '2026-06', 'Другая аудитория');
app.saveCampaignNote('Google', '2026-05', 'Карты');
assert.equal(app.campaignNoteText('Instagram', '2026-05'), 'Женщины 25–45\nРадиус 3 км');
assert.equal(app.campaignNoteText('Instagram'), 'Общая стратегия');
app = session(); // Reloading preserves notes and does not reuse in-memory page state.
assert.equal(app.campaignNoteText('Instagram', '2026-06'), 'Другая аудитория');
app.DB.location.id = 2;
assert.equal(app.campaignNoteText('Instagram', '2026-05'), '');
app.saveCampaignNote('Instagram', '2026-05', 'Другой филиал');
app.DB.location.id = 1;
assert.equal(app.campaignNoteText('Instagram', '2026-05'), 'Женщины 25–45\nРадиус 3 км');
const scope = app.campaignNotesStorageKey();
app.DB.connection_id = 'account-b';
assert.equal(app.campaignNoteText('Instagram'), '');
assert.throws(() => app.saveCampaignNote('Instagram', '', 'Wrong account', scope));
app.DB.connection_id = 'account-a';
app.saveCampaignNote('Instagram', '2026-05', '  \n ');
assert.equal(app.campaignNoteText('Instagram', '2026-05'), '');
assert.equal(app.campaignNoteText('Instagram', '2026-06'), 'Другая аудитория');
assert.equal(app.campaignNoteText('Google', '2026-05'), 'Карты');
app.saveCampaignNote('Instagram', '2026-05', '\"><img src=x onerror="evil()">');
const button = app.campaignNoteButton('Instagram', '2026-05');
assert(button.includes('has-note'));
assert(button.includes('&lt;img'));
assert(!button.includes('<img'));
assert(!app.campaignNoteButton('Instagram', '2026-07').includes('has-note'));
assert.throws(() => app.saveCampaignNote('Instagram', '', 'a'.repeat(5001)));
storage.setItem = () => { throw Error('QuotaExceeded'); };
assert.throws(() => app.saveCampaignNote('Instagram', '', 'Must not replace the saved text'));
assert.equal(app.campaignNoteText('Instagram'), 'Общая стратегия');
storage.setItem = (key, value) => memory.set(key, value);
memory.set(scope, '[1,2]');
assert.throws(() => app.saveCampaignNote('Instagram', '', 'Must not overwrite damaged storage'));
assert.equal(memory.get(scope), '[1,2]');
app.DB.location = {};
assert.equal(app.campaignNoteScopeIsCurrent(scope), false);
console.log('Passed: campaign/month/account/location separation, persistence, clearing, escaped previews, length limit, failed writes and damaged storage.');
